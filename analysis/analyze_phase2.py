"""Phase 2 analysis.

  python3 analysis/analyze_phase2.py   -> results/analysis/phase2_summary.md (+ phase2_static.csv, phase2_dynamic.csv)

Static runs (p2a/p2e/p2q/p2b/p2diag): unit = per-run mean round time over successful rounds 2..R (as Phase 1).
Dynamic runs (p2d): unit = per-run total wall time to 20 successful rounds; routers are compared with the best
fixed protocol of the same trace and repetition (identical trace) by Wilcoxon signed-rank over repetitions.
"""
import json, math
from pathlib import Path
import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "runs"
OUT = ROOT / "results" / "analysis"


def expected_round(d):
    import sys
    sys.path.insert(0, str(ROOT / "orchestrator"))
    from run_cells import expected_round_s
    return expected_round_s(d)


def load_static(prefix="p2"):
    rows = []
    for f in sorted(RUNS.glob(f"{prefix}*.json")):
        d = json.loads(f.read_text())
        if d.get("trace"):
            continue
        rr = [r for r in d["rows"] if r.get("r", 0) >= 2]
        ts = [r["T_round"] for r in rr if r.get("ok") and r.get("T_round")]
        # effective cost: wall time of rounds 2..R including failed rounds (from consecutive round start times; the
        # last round's own time, or its round timeout if it failed) per successful round
        allr = d["rows"]; dur = []
        for a, b in zip(allr, allr[1:] + [None]):
            if a.get("r", 0) < 2:
                continue
            if b is not None:
                dur.append(b["t0"] - a["t0"])
            else:
                dur.append(a["T_round"] if a.get("ok") and a.get("T_round") else max(60.0, 6 * expected_round(d) + 20))
        eff = sum(dur) / len(ts) if ts else np.inf  # no successful round: infinitely costly (not dropped)
        rows.append(dict(id=d["id"], series=d["id"].split("_")[0], eff_s=eff, cell=d["cell"], arm=d.get("arm", d["proto"]), proto=d["proto"],
                         cc=d.get("cc", "bbr"), rep=d["rep"], round_s=np.mean(ts) if ts else np.nan,
                         fail_frac=1 - len(ts) / max(len(rr), 1), n_rounds=len(rr),
                         attempts=np.mean([c.get("attempts") or 0 for r in rr for c in r["clients"].values()]) if rr else np.nan))
    return pd.DataFrame(rows)


def load_dynamic():
    rows, rounds = [], []
    for f in sorted(RUNS.glob("p2d_*.json")):
        d = json.loads(f.read_text())
        summ = d["rows"][-1]; rr = [r for r in d["rows"] if not r.get("summary")]
        switches = sum(1 for a, b in zip(rr, rr[1:]) if a["proto"] != b["proto"])
        rows.append(dict(id=d["id"], trace=d["cell"], arm=d["arm"], rep=d["rep"], total_s=summ["s_per_round"] or np.inf,
                         ok_rounds=summ["ok_rounds"], attempted=summ["attempted"], switches=switches,
                         failed=sum(1 for r in rr if not r["ok"]),
                         share=json.dumps(pd.Series([r["proto"] for r in rr]).value_counts(normalize=True).round(2).to_dict())))
        for r in rr:
            rounds.append(dict(id=d["id"], trace=d["cell"], arm=d["arm"], rep=d["rep"], k=r["r"], proto=r["proto"], state=r["state"],
                               ok=r["ok"], elapsed=r["elapsed"], changes=len(r["changes"]),
                               ho=any(h for _, _, h in r["changes"])))
    return pd.DataFrame(rows), pd.DataFrame(rounds)


def fmt(m, s):
    return f"{m:.1f} ± {s:.1f}" if not math.isnan(m) else "–"


def static_table(df, title, arms):
    out = [f"### {title}", "", "| Cell | " + " | ".join(arms) + " | best | KW p |", "|---|" + "---|" * (len(arms) + 2)]
    for cell, g in df.groupby("cell", sort=False):
        cols, data = [], []
        for a in arms:
            x = g[g.arm == a]
            if len(x) == 0:
                cols.append("–"); continue
            v = x.round_s.dropna()
            ff = x.fail_frac.mean()
            cols.append(f"{fmt(v.median(), v.std() if len(v) > 1 else 0)} (n={len(x)}{', %d %% fail' % round(100 * ff) if ff > 0 else ''})")
            if len(v):
                data.append(v.values)
        meds = {a: g[g.arm == a].round_s.median() for a in arms if (g.arm == a).any()}
        best = min(meds, key=lambda a: meds[a] if not math.isnan(meds[a]) else 1e18)
        try:
            p = stats.kruskal(*data).pvalue if len(data) > 1 else float("nan")
        except ValueError:
            p = float("nan")
        out.append(f"| {cell} | " + " | ".join(cols) + f" | {best} | {p:.3g} |")
    return out + [""]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    md = ["# Phase 2 results (generated by analysis/analyze_phase2.py)", "",
          "Static cells: median ± SD over runs of the per-run mean round time (rounds 2..R, successful rounds), seconds. "
          "All protocols use CUBIC unless the table says BBR.", ""]
    st = load_static()
    if len(st):
        st.to_csv(OUT / "phase2_static.csv", index=False)
        diag = st[st.series == "p2diag"]
        if len(diag):
            md += static_table(diag, "gRPC diagnosis (HTTP/2 flow-control window)", ["mqtt", "grpc", "grpcwin16M"])
        a = st[st.series.isin(["p2a", "p2e"])]
        if len(a):
            md += static_table(a, "Static anchors and event cells (CUBIC)", ["mqtt", "amqp", "grpc", "http3"])
        q = st[st.series.isin(["p2a", "p2e", "p2q"]) & st.cell.isin(st[st.series == "p2q"].cell.unique())]
        if (st.series == "p2q").any():
            md += static_table(q, "QUIC stacks (CUBIC): HTTP/3 on quic-go, raw quic-go, raw quinn; TCP references",
                               ["mqtt", "grpc", "http3", "quic", "quinn"])
        b = st[st.series == "p2b"]
        if len(b):
            md += static_table(b, "BBR everywhere: TCP-BBR vs quinn-BBR", ["mqtt", "amqp", "grpc", "quinn-bbr"])
    dy, dr = load_dynamic()
    if len(dy):
        dy.to_csv(OUT / "phase2_dynamic.csv", index=False); dr.to_csv(OUT / "phase2_dynamic_rounds.csv", index=False)
        md += dynamic_section(dy, dr)
    (OUT / "phase2_summary.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


def dynamic_section(dy, dr):
    fixed = ["mqtt", "amqp", "grpc", "http3"]; routers = ["oracle", "reactive", "ducb"]
    md = ["### Dynamic traces: seconds per successful round over a fixed 360 s stretch of trace (median over repetitions; lower is better)", "",
          "| Trace | reps | " + " | ".join(fixed + routers) + " | best fixed | best router vs best fixed (+ = router faster) |",
          "|---|---|" + "---|" * (len(fixed) + len(routers) + 2)]
    tests = []
    for tr, g in dy.groupby("trace"):
        piv = g.pivot_table(index="rep", columns="arm", values="total_s")
        full = piv.dropna()
        meds = piv.median()
        bf = meds[[a for a in fixed if a in meds]].idxmin() if any(a in meds for a in fixed) else None
        cells = []
        for a in fixed + routers:
            if a not in piv:
                cells.append("–"); continue
            sw = g[g.arm == a].switches.median(); fl = g[g.arm == a].failed.sum()
            cells.append(f"{meds[a]:.1f}" + (f" ({sw:.0f} sw)" if a in routers else "") + (f" [{fl} failed]" if fl else ""))
        voa = ""
        if bf and any(r in meds for r in routers):
            br = min((r for r in routers if r in meds), key=lambda r: meds[r])
            voa = f"{br}: {100 * (meds[bf] - meds[br]) / meds[bf]:+.1f} %"
        md.append(f"| {tr} | {len(piv)} | " + " | ".join(cells) + f" | {bf} | {voa} |")
        # per-rep best fixed (in hindsight) vs each router, paired on identical traces
        if len(full) >= 3 and all(a in full for a in fixed):
            hind = full[fixed].min(axis=1); stat_bf = full[bf]
            for r in routers:
                if r in full:
                    for ref_name, ref in (("best fixed (overall)", stat_bf), ("best fixed per rep (hindsight)", hind)):
                        d = (full[r] - ref).values
                        p = stats.wilcoxon(full[r], ref).pvalue if len(d) >= 5 and np.any(d != 0) else float("nan")
                        tests.append(f"| {tr} | {r} | {ref_name} | {np.median(100 * d / ref.values):+.1f} % | {p:.3g} | {len(d)} |")
    md += ["", "Router minus reference, paired by repetition (identical trace); negative = router faster. "
           "Wilcoxon signed-rank needs n ≥ 5.", "", "| Trace | Router | Reference | median Δ | Wilcoxon p | n |", "|---|---|---|---|---|---|"] + tests
    # pooled over traces: each (trace, rep) is one pair on an identical trace; log ratio router / best fixed protocol
    md += ["", "Pooled over the four traces (each trace x repetition is one pair on an identical trace). Note: with n = 5 the "
           "two-sided Wilcoxon cannot go below p = 0.0625, hence the pooled test. Ratio = router / fixed HTTP/3 "
           "(geometric mean); 'slower in' = pairs where the router needed more time per round; Wilcoxon signed-rank on the log ratios.", "",
           "| Router | pairs | geometric-mean ratio vs fixed HTTP/3 | slower in | Wilcoxon p (two-sided) |", "|---|---|---|---|---|"]
    for r in routers:
        x, y = [], []
        for tr, g in dy.groupby("trace"):
            piv = g.pivot_table(index="rep", columns="arm", values="total_s")
            if r not in piv or "http3" not in piv:      # arm still being re-run for this trace
                continue
            piv = piv.dropna(subset=[r, "http3"])
            x += list(piv[r]); y += list(piv["http3"])
        x, y = np.array(x), np.array(y)
        if len(x) >= 5:
            lr = np.log(x / y)
            md.append(f"| {r} | {len(x)} | {np.exp(lr.mean()):.3f} | {int((x > y).sum())}/{len(x)} | {stats.wilcoxon(lr).pvalue:.2g} |")
    # per-state round time of the fixed arms inside the traces (state at round start, rounds without state change)
    clean = dr[(dr.arm.isin(fixed)) & (dr.changes == 0) & dr.ok]
    if len(clean):
        t = clean.pivot_table(index="state", columns="arm", values="elapsed", aggfunc="median").round(1)
        md += ["", "Fixed arms inside the traces, median round time by link state (rounds with no state change):", "",
               t.to_markdown()]
    return md + [""]


if __name__ == "__main__":
    main()
